"""Build the particle sprite atlas for the web game from the CC0 "Pixel Art Atlas 1.4M" dataset
(https://huggingface.co/datasets/Angais/pixel-art-atlas-1.4m, CC0 1.0, by Angais).

Picks hand-chosen 16x16 sprites (subject + nth occurrence in the shard) and writes
web/src/fxAtlas.js with the atlas embedded as a data URI plus the frame index table.

Usage:
  curl -L -o train-000.parquet https://huggingface.co/datasets/Angais/pixel-art-atlas-1.4m/resolve/main/data/train-000.parquet
  pip install pyarrow pillow
  python3 tools/build_fx_atlas.py train-000.parquet
"""
import base64, io, json, os, sys
import pyarrow.parquet as pq
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GRID, CELL = 8, 16

# frame name -> (subject, nth occurrence in train-000)
PICKS = {
    "fire_proj": ("fireball", 0), "fire_bit": ("flame", 0), "ember": ("ember", 2),
    "ice_proj": ("ice shard", 0), "ice_bit": ("snowflake", 0),
    "wind_proj": ("feather", 2), "wind_bit": ("cloud", 11), "tornado": ("tornado", 0),
    "earth_proj": ("rock", 0), "earth_bit": ("pebble", 0),
    "water_proj": ("water drop", 0), "water_bit": ("water drop", 7),
    "lightning_proj": ("lightning bolt", 5), "lightning_bit": ("spark burst", 1),
    "metal_proj": ("gear cog", 3), "metal_bit": ("bolt", 3),
    "poison_proj": ("poison drop icon", 2), "poison_bit": ("ball lightning", 5),
    "psychic_proj": ("magic swirl", 0), "psychic_bit": ("magic sparkle", 3),
    "undead_proj": ("skull icon", 6), "undead_bit": ("bone", 2),
    "light_proj": ("star sparkle", 3), "light_bit": ("sun", 2),
    "shadow_proj": ("magic swirl", 5), "shadow_bit": ("ghost", 1),
    "neutral_proj": ("magic sparkle", 7), "neutral_bit": ("star sparkle", 4),
    "hit": ("spark burst", 0), "hit_hot": ("spark burst", 6), "crit": ("star sparkle", 9),
    "heal": ("heart icon", 7), "comet": ("comet", 2), "icicle": ("ice crystal", 0),
    "boulder": ("rock", 8), "bolt_strike": ("lightning bolt", 0), "sunburst": ("sun", 0), "geyser": ("water drop", 3),
}


def main():
    t = pq.read_table(sys.argv[1], columns=["image", "subject"])
    subj = t.column("subject").to_pylist()
    img = t.column("image")
    want = {}
    for name, (s, n) in PICKS.items():
        want.setdefault(s, {})[n] = name
    seen, found = {}, {}
    for i, s in enumerate(subj):
        if s not in want:
            continue
        k = seen.get(s, 0)
        seen[s] = k + 1
        if k in want[s]:
            found[want[s][k]] = Image.open(io.BytesIO(img[i].as_py()["bytes"])).convert("RGBA")
    atlas = Image.new("RGBA", (GRID * CELL, GRID * CELL), (0, 0, 0, 0))
    frames = {}
    # frame 0: soft round glow, frame 1: hard dot (generated)
    glow = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    for y in range(CELL):
        for x in range(CELL):
            d = ((x - 7.5) ** 2 + (y - 7.5) ** 2) ** 0.5 / 7.5
            glow.putpixel((x, y), (255, 255, 255, int(255 * max(0, 1 - d) ** 1.6)))
    atlas.paste(glow, (0, 0)); frames["glow"] = 0
    dot = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0)); ImageDraw.Draw(dot).ellipse((4, 4, 11, 11), fill=(255, 255, 255, 255))
    atlas.paste(dot, (CELL, 0)); frames["dot"] = 1
    for k, name in enumerate(PICKS, start=2):
        if name not in found:
            raise SystemExit(f"missing sprite for {name}: {PICKS[name]}")
        atlas.paste(found[name], ((k % GRID) * CELL, (k // GRID) * CELL))
        frames[name] = k
    buf = io.BytesIO(); atlas.save(buf, "PNG", optimize=True)
    out = os.path.join(ROOT, "web", "src", "fxAtlas.js")
    with open(out, "w") as f:
        f.write("// Generated by tools/build_fx_atlas.py. Sprites: Pixel Art Atlas 1.4M by Angais (CC0 1.0),\n")
        f.write("// https://huggingface.co/datasets/Angais/pixel-art-atlas-1.4m\n")
        f.write(f"export const ATLAS_GRID = {GRID};\n")
        f.write(f"export const FRAMES = {json.dumps(frames)};\n")
        f.write(f"export const ATLAS_URL = 'data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}';\n")
    atlas.resize((GRID * CELL * 4, GRID * CELL * 4), Image.NEAREST).save(out.replace("fxAtlas.js", "fxAtlas.preview.png"))
    print(f"wrote {out}: {len(frames)} frames, {len(buf.getvalue())} bytes")


if __name__ == "__main__":
    main()
